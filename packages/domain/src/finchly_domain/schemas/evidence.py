"""Evidence provenance records conforming to ADR-010 §6 and AGENTS.md §10."""

from enum import StrEnum
from typing import Literal
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field, field_validator


class TextSource(StrEnum):
    """Origin of extracted text."""

    EMBEDDED = "embedded"
    OCR = "ocr"


class EvidenceMethod(StrEnum):
    """Method used to extract or derive the field."""

    EMBEDDED = "embedded"
    OCR_LLM = "ocr_llm"
    RULES = "rules"
    DERIVED = "derived"
    HUMAN = "human"


class SupportStatus(StrEnum):
    """Status confirming value-support check results."""

    SUPPORTED = "supported"
    UNSUPPORTED = "unsupported"
    DERIVED = "derived"


class Evidence(BaseModel):
    """Verifiable evidence record resolving to source text blocks."""

    model_config = ConfigDict(frozen=True)

    evidence_id: str = Field(
        default_factory=lambda: str(uuid4()),
        description="Unique identifier for this evidence record.",
    )
    block_ids: list[str] = Field(
        default_factory=list,
        description="List of persisted OCR or embedded text block IDs supporting this field.",
    )
    page: int = Field(ge=1, description="Source page number (1-indexed).")
    bbox: list[float] = Field(
        description="Bounding box [ymin, xmin, ymax, xmax] in original_page_normalized coordinates [0.0, 1.0].",
    )
    coordinate_space: Literal["original_page_normalized"] = Field(
        default="original_page_normalized",
        description="Coordinate space fixed to original_page_normalized.",
    )
    text_span: str = Field(description="Exact cited text span from the source document.")
    source_engine: str = Field(
        description="Extraction or OCR engine identifier (e.g. 'tesseract', 'pypdf')."
    )
    text_source: TextSource = Field(description="Underlying source mechanism (embedded or ocr).")
    method: EvidenceMethod = Field(
        description="Processing method (embedded, ocr_llm, rules, derived, human)."
    )
    support_status: SupportStatus = Field(
        default=SupportStatus.SUPPORTED,
        description="Support disposition after value-support verification.",
    )
    model_run_id: str | None = Field(
        default=None,
        description="Reference to pinned model_runs row if generated by an LLM run.",
    )
    confidence_raw: float | None = Field(
        default=None,
        description="Nullable raw model self-reported score (never used as probability).",
    )
    confidence_calibrated: float | None = Field(
        default=None,
        description="Nullable calibrated probability; remains null until ADR-014 criteria are met.",
    )

    @field_validator("bbox")
    @classmethod
    def validate_bounding_box(cls, v: list[float]) -> list[float]:
        """Validate bbox has 4 coordinates in [0.0, 1.0] with ymin <= ymax and xmin <= xmax."""
        if len(v) != 4:
            raise ValueError(
                f"Bounding box must contain exactly 4 coordinates [ymin, xmin, ymax, xmax], got {len(v)}."
            )

        ymin, xmin, ymax, xmax = v
        for name, coord in (("ymin", ymin), ("xmin", xmin), ("ymax", ymax), ("xmax", xmax)):
            if not 0.0 <= coord <= 1.0:
                raise ValueError(
                    f"Coordinate {name}={coord} is out of normalized range [0.0, 1.0]."
                )

        if ymin > ymax:
            raise ValueError(f"Invalid bounding box: ymin ({ymin}) cannot exceed ymax ({ymax}).")
        if xmin > xmax:
            raise ValueError(f"Invalid bounding box: xmin ({xmin}) cannot exceed xmax ({xmax}).")

        return v
